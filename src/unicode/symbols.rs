/// Grapheme cluster variants for quick identification.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum GraphType {
    /// Prepend characters (rare, Mongolian)
    Prepend,
    /// Carriage return
    CR,
    /// Line feed
    LF,
    /// Control characters
    Control,
    /// Extenders (combining marks, emoji modifiers)
    Extend,
    /// Emoji modifier sequences and friends
    ExtendedPictographic,
    /// Regional indicator flags (A-Z regionals)
    RegionalIndicator,
    /// Spacing marks
    SpacingMark,
    /// Leading jamo (Hangul)
    L,
    /// Vowel jamo (Hangul)
    V,
    /// Trailing jamo (Hangul)
    T,
    /// LV syllable (Hangul)
    LV,
    /// LVT syllable (Hangul)
    LVT,
    /// Zero-width joiner
    ZWJ,
    /// Literally any other character
    Other,
}
