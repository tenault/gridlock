/// Grapheme cluster variants for quick identification.
///
/// Each variant is codified with a max of 2-letters to assist spacing in lookup arrays.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum GraphType {
    /// Prepend character
    P,
    /// Carriage return
    CR,
    /// Line feed
    LF,
    /// Control character
    C,
    /// Extender (combining marks, emoji modifiers)
    E,
    /// Extended pictogrpahic (emoji modifier sequences and friends)
    EP,
    /// Regional indicator (A-Z regional flags)
    RI,
    /// Spacing mark
    SM,
    /// Leading jamo (Hangul)
    L,
    /// Vowel jamo (Hangul)
    V,
    /// Trailing jamo (Hangul)
    T,
    /// LV syllable (Hangul)
    LV,
    /// LVT syllable (Hangul)
    LT,
    /// Zero-width joiner
    ZW,
    /// Indic conjunct break consonant
    IC,
    /// Indic conjunct break linker
    IL,
    /// Indic conjunct break extender
    IE,
    /// Literally any other character
    O,
}
